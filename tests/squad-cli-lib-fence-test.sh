#!/usr/bin/env bash
# ZIP のルートから bash tests/squad-cli-lib-fence-test.sh で実行する。
# squad-cli-lib の制御記録の読み取りが、囲みのコード（CommonMark 0.31.2 の 4.5）の規則に沿って行を読み飛ばすかを、規則ごとの表で確かめる。
# 設計は docs/review-next-step.md の「制御記録の読み方」にある。設計が決めているのは「行頭に空白がない」「`>` の引用の行は読まない」「囲んだ部分の行は読まない」で、囲みの開始と終了の細かい条件は CommonMark に合わせる。
# 表の 1 行は、囲みの行を並べた本文の後ろに、制御記録の 2 行（修正の依頼・前の回）を置き、その 2 行が制御記録として読まれるか（読む）、囲みの中として読まれないか（読まない）を期待する。
# 箇条書きの中の囲みは設計が決めていないので、表に入れない。
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"
mkdir -p tmp
test_dir=$(mktemp -d "$PWD/tmp/cli-lib-fence-test.XXXXXX")
trap 'rm -rf -- "$test_dir"' EXIT
source "$root/common/monitor/squad-cli-lib"

file=$test_dir/comments.json
bt='```'
b4='````'
tl='~~~'
t4='~~~~'
sp4='    '
tab=$'\t'
control=$'修正の依頼: 直す\n前の回: r1'

# 表を流す。説明は規則の番号つきで、失敗したときにどの規則かが分かるようにする。
rows=0
failed=0
row() { # 規則 説明 期待（読む|読まない） 囲みの行（改行区切り）
	local rule=$1 what=$2 want=$3 body=$4 got
	jq -n --arg body "$body"$'\n'"$control" '[
		{id: "r1", author_id: "L", author_type: "agent", created_at: "2026-11-10T12:00:01Z",
		 content: "確認するコミット: abc1234\n返事を待つ役: [@qa](mention://agent/qa)\n観点: qa（テスト）"},
		{id: "d1", author_id: "qa", author_type: "agent", created_at: "2026-11-10T12:00:02Z",
		 content: "/note\n返事の待ち: 次の依頼を決めます"},
		{id: "x", author_id: "L", author_type: "agent", created_at: "2026-11-10T12:00:03Z", content: $body}]' >"$file"
	got=$(squad_cli_control analyze "$(<"$file")" '["L"]' '["P"]' | jq -r '[.controls[] | select(.id == "x" and .kind == "fix")] | if length > 0 then "読む" else "読まない" end')
	rows=$((rows + 1))
	[[ $got == "$want" ]] || {
		printf '規則 %s（%s）: %s のはずが %s\n本文:\n%s\n' "$rule" "$what" "$want" "$got" "$body" >&2
		failed=$((failed + 1))
	}
}

# ---- 開始: 字下げは 0〜3 個。4 個以上は囲みの開始ではない。
row 開始-字下げ 'バッククォート 3 個、字下げ 0 個で開始する' 読まない "$bt"
row 開始-字下げ 'バッククォート 3 個、字下げ 3 個で開始する' 読まない "   $bt"
row 開始-字下げ 'バッククォート 3 個、字下げ 4 個は開始でない' 読む "${sp4}${bt}"
row 開始-字下げ 'バッククォート 3 個、字下げ 8 個は開始でない' 読む "${sp4}${sp4}${bt}"
row 開始-字下げ 'バッククォート 3 個、タブ 1 個は字下げ 4 個で開始でない' 読む "${tab}${bt}"
row 開始-字下げ 'チルダ 3 個、字下げ 3 個で開始する' 読まない "   ${tl}"
row 開始-字下げ 'チルダ 3 個、字下げ 4 個は開始でない' 読む "${sp4}${tl}"
row 開始-字下げ 'バッククォート 3 個、空白 2 個とタブで字下げ 4 個以上は開始でない' 読む "  ${tab}${bt}"

# ---- 開始: バッククォートの囲みの情報文字列にはバッククォートを含められない。チルダの囲みは含められる。
row 開始-情報文字列 'バッククォートの囲みの情報文字列（text）で開始する' 読まない "${bt}text"
row 開始-情報文字列 'バッククォートの囲みの情報文字列にバッククォートを含めば開始でない' 読む "${bt} a\`b"
row 開始-情報文字列 '同じ行で閉じたバッククォート（インラインのコード）は開始でない' 読む "${bt}x${bt}"
row 開始-情報文字列 '4 個のバッククォートの情報文字列にバッククォートを含めば開始でない' 読む "${b4} \`"
row 開始-情報文字列 'チルダの囲みの情報文字列にバッククォートを含んでも開始する' 読まない "${tl} a\`b"
row 開始-情報文字列 'チルダの囲みの情報文字列にチルダを含んでも開始する' 読まない "${tl} a~b"

# ---- 開始: 長さは 3 個以上。種類（バッククォートとチルダ）を保つ。
row 開始-長さ 'バッククォート 2 個は開始でない' 読む '``'
row 開始-長さ 'チルダ 2 個は開始でない' 読む '~~'
row 開始-長さ 'バッククォート 1 個は開始でない' 読む '`'
row 開始-長さ 'バッククォート 5 個で開始する' 読まない '`````'
row 開始-長さ 'チルダ 4 個で開始する' 読まない "${t4}"
row 開始-種類 'バッククォートとチルダを混ぜた行は開始でない' 読む '`~`'

# ---- 終了: 開始と同じ種類で、開始以上の長さ。字下げは 0〜3 個。後ろは空白のみ。
row 終了-長さ '同じ長さで閉じる（バッククォート）' 読む "${bt}"$'\n'x$'\n'"${bt}"
row 終了-長さ '開始より長い行で閉じる（バッククォート）' 読む "${bt}"$'\n'x$'\n''`````'
row 終了-長さ '開始より短い行では閉じない（4 個の中の 3 個）' 読まない "${b4}"$'\n'x$'\n'"${bt}"
row 終了-長さ '開始より短い行が続いても閉じない（4 個の中の 3 個の囲み）' 読まない "${b4}"$'\n'"${bt}"$'\n'x$'\n'"${bt}"
row 終了-長さ '4 個の中の 3 個の囲みを経て、4 個で閉じる' 読む "${b4}"$'\n'"${bt}"$'\n'x$'\n'"${bt}"$'\n'"${b4}"
row 終了-長さ '同じ長さで閉じる（チルダ）' 読む "${tl}"$'\n'x$'\n'"${tl}"
row 終了-長さ '開始より短い行では閉じない（チルダ 4 個の中の 3 個）' 読まない "${t4}"$'\n'"${tl}"
row 終了-種類 'チルダで始めた囲みは、バッククォートでは閉じない' 読まない "${tl}"$'\n'"${bt}"
row 終了-種類 'バッククォートで始めた囲みは、チルダでは閉じない' 読まない "${bt}"$'\n'"${tl}"
row 終了-字下げ '字下げ 3 個の行で閉じる' 読む "${bt}"$'\n'x$'\n'"   ${bt}"
row 終了-字下げ '字下げ 4 個の行では閉じない' 読まない "${bt}"$'\n'x$'\n'"${sp4}${bt}"
row 終了-字下げ '字下げ 4 個の行では閉じない（4 個の囲み）' 読まない "${b4}markdown"$'\n'"${sp4}${b4}"
row 終了-字下げ 'タブ 1 個の行では閉じない' 読まない "${bt}"$'\n'x$'\n'"${tab}${bt}"
row 終了-字下げ '字下げ 4 個の終了風の行のあとで、字下げ 0 個の行で閉じる' 読む "${b4}"$'\n'"${sp4}${b4}"$'\n'"${b4}"
row 終了-字下げ 'チルダの囲みも、字下げ 4 個の行では閉じない' 読まない "${tl}"$'\n'"${sp4}${tl}"
row 終了-後ろ '後ろが空白だけの行で閉じる' 読む "${bt}"$'\n'x$'\n'"${bt}   "
row 終了-後ろ '後ろがタブだけの行で閉じる' 読む "${bt}"$'\n'x$'\n'"${bt}${tab}"
row 終了-後ろ '後ろに情報文字列がある行では閉じない' 読まない "${bt}"$'\n'x$'\n'"${bt} text"
row 終了-後ろ '後ろに同じ文字が空白をはさんで続く行では閉じない' 読まない "${bt}"$'\n'x$'\n'"${bt} ${bt}"
row 終了-後ろ '後ろが改行しない空白（NBSP）の行では閉じない' 読まない "${bt}"$'\n'x$'\n'"${bt}"$' '
row 終了-後ろ '後ろが別の文字の行では閉じない' 読まない "${bt}"$'\n'x$'\n'"${bt}x"

# ---- 閉じないときは、文書の末尾まで囲みの中として扱う。
row 閉じない '閉じない囲みの後ろの制御記録は読まない' 読まない "${bt}"$'\n'x
row 閉じない '閉じない 4 個の囲みを 3 個で閉じようとしても末尾まで囲み' 読まない "${b4}"$'\n'x$'\n'"${bt}"

# ---- 引用の行は、設計のとおり読まない。引用の中の囲みの開始と終了は、囲みと数えない。
row 引用 '引用の行の囲みの開始は、囲みを始めない（引用のあとの行は囲みの外）' 読む "> ${bt}"$'\n'"> x"
row 引用 '囲みの中の引用の行の終了風の行では、囲みは閉じない' 読まない "${bt}"$'\n'"> ${bt}"
row 引用 '囲みの中の引用の行の終了風の行では、囲みは閉じない（空白なし）' 読まない "${bt}"$'\n'">${bt}"

# 囲みのない本文では、制御記録の行を読む（表の期待が「読まない」になるのは囲みのせいだけ、という前提）。
row 前提 '囲みのない本文の制御記録は読む' 読む 'ふつうの文です'
[[ $failed -eq 0 ]] && echo "PASS fence: 囲みのコードの規則 ${rows} 行（開始の字下げ・情報文字列・長さ・種類、終了の長さ・種類・字下げ・後ろ、閉じない、引用、前提）を、制御記録の読み取りが守る"

[[ $failed -eq 0 ]] || {
	echo "FAIL fence: ${failed} 行が規則に合わない" >&2
	exit 1
}
